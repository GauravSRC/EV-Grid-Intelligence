"""Baseline (status-quo) calibration to today's KPIs using STRUCTURAL parameters only.

Targets: reliability 78% (+-1pp), losses 10% (+-0.5pp), company EBITDA ~12.5% with >=1 cluster below 12%.
Levers (bisection, representative weeks): network.hub_misalloc_gamma -> R; losses.charger_k1 (P0 pinned 0.5%) -> loss %;
opex.fixed_opex_cr solved in closed form -> EBITDA.  The result is written to config/calibrated.yaml and FROZEN
before any AI run; AI and Baseline then share identical physics, data and random draws.
"""
from __future__ import annotations

import copy
import logging
from typing import Callable, Dict, Tuple

import yaml

from evgrid.config import CONFIG_DIR, load_config
from evgrid.simulation.kpis import fixed_opex_alloc, kpis
from evgrid.simulation.policies import BASELINE
from evgrid.simulation.runner import Runner, rep_week_days

log = logging.getLogger(__name__)


def _bisect(f: Callable[[float], float], lo: float, hi: float, target: float, increasing: bool, tol: float, iters: int) -> Tuple[float, float]:
    x, v = lo, f(lo)
    for _ in range(iters):
        x = 0.5 * (lo + hi)
        v = f(x)
        if abs(v - target) <= tol:
            break
        if (v < target) == increasing:
            lo = x
        else:
            hi = x
    return x, v


def calibrate(runner: Runner, iters: int = 15) -> Dict:
    days, w = rep_week_days()
    base = load_config(calibrated=False)
    trace = []

    def run(over: dict) -> dict:
        cfg = load_config(calibrated=False, overrides=over)
        df = runner.run(BASELINE, days, cfg=cfg, weights=w)
        k = kpis(df, cfg, fixed_opex_alloc(cfg))
        trace.append(dict(over=copy.deepcopy(over), R=k["R"], loss=k["loss_pct"]))
        log.info("calib %s -> R %.4f loss %.4f", over, k["R"], k["loss_pct"])
        return k

    over: Dict = {"network": {"hub_misalloc_gamma": 1.0}, "losses": {"charger_p0_frac": 0.005, "charger_k1": base["losses"]["charger_k1"]}}

    def f_r(g: float) -> float:
        over["network"]["hub_misalloc_gamma"] = g
        return run(over)["R"]

    g, r = _bisect(f_r, 1.0, 6.0, 0.78, increasing=False, tol=0.004, iters=iters)
    over["network"]["hub_misalloc_gamma"] = round(g, 4)

    def f_l(k1: float) -> float:  # P0 pinned at 0.5% (range 0.5-1%); calibrate proportional conversion loss
        over["losses"]["charger_k1"] = k1
        return run(over)["loss_pct"]

    k1, lv = _bisect(f_l, 0.015, 0.05, 0.100, increasing=True, tol=0.002, iters=iters)
    over["losses"]["charger_k1"] = round(k1, 5)
    # closed-form fixed opex so that company EBITDA margin = 12.5% (fixed opex is policy-independent)
    over["opex"] = {"fixed_opex_cr": 0.0}
    k0 = run(over)
    fixed = k0["revenue_cr"] - k0["energy_cost_cr"] - k0["opex_var_cr"] - 0.125 * k0["revenue_cr"]
    over["opex"]["fixed_opex_cr"] = round(float(fixed), 2)
    cfg = load_config(calibrated=False, overrides=over)
    df = runner.run(BASELINE, days, cfg=cfg, weights=w)
    from evgrid.simulation.kpis import kpi_table

    tab = kpi_table(df, cfg, fixed_opex_alloc(cfg))
    summary = {c: dict(R=v["R"], loss_pct=v["loss_pct"], ebitda_margin=v["ebitda_margin"]) for c, v in tab.items()}
    doc = {
        "note": "FROZEN baseline calibration (structural parameters only). Generated by evgrid/simulation/calibrate.py; "
                "do not edit by hand. AI policy runs use these values unchanged.",
        "overrides": over,
        "calibration_check_rep_weeks": summary,
        "trace": [{"R": round(t["R"], 4), "loss": round(t["loss"], 4), **{k: v for d in t["over"].values() for k, v in d.items()}} for t in trace],
    }
    with open(CONFIG_DIR / "calibrated.yaml", "w", encoding="utf-8") as fh:
        yaml.safe_dump(doc, fh, sort_keys=False)
    log.info("calibrated: %s | overall %s", over, summary["overall"])
    return doc
